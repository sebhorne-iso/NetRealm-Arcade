function distro(year) {
  if (year < 1999) return { name: 'Red Hat Linux release 4.2 (Biltmore)', kernel: '2.0.30', short: 'Red Hat Linux 4.2' };
  if (year < 2004) return { name: 'Red Hat Linux release 7.3 (Valhalla)', kernel: '2.4.18-3', short: 'Red Hat Linux 7.3' };
  if (year < 2010) return { name: 'CentOS release 5.4 (Final)', kernel: '2.6.18-164.el5', short: 'CentOS 5.4' };
  if (year < 2016) return { name: 'Ubuntu 14.04.5 LTS', kernel: '3.13.0-170-generic', short: 'Ubuntu 14.04.5 LTS' };
  if (year < 2021) return { name: 'Ubuntu 18.04.6 LTS', kernel: '4.15.0-213-generic', short: 'Ubuntu 18.04.6 LTS' };
  return { name: 'Ubuntu 22.04.4 LTS', kernel: '5.15.0-105-generic', short: 'Ubuntu 22.04.4 LTS' };
}
const isJump = (s) => s.host?.kind === 'jump';
const ip3 = (n) => n.toFixed(3);
export function jumpState(world) {
  world.jumpState = world.jumpState || { known: {}, hist: [] };
  return world.jumpState;
}
// /etc/hosts on the jump host (generated from IPAM, including any stale records)
export function etcHosts(world) {
  const out = [['127.0.0.1', 'localhost'], ['10.250.0.10', 'jump01']];
  const errs = world.design.docErrors || [];
  for (const [id, ip] of Object.entries(world.design.mgmt)) {
    const d = world.devices[id];
    if (!d) continue;
    const e = errs.find((x) => x.doc === 'ipam' && x.kind === 'mgmt' && x.dev === id);
    out.push([e ? e.wrong : ip, d.hostname]);
  }
  return out;
}
function resolve(s, name) {
  if (/^\d+\.\d+\.\d+\.\d+$/.test(name)) return name;
  if (!isJump(s)) {
    const h = Object.values(s.world.hosts).find((x) => x.name === name);
    if (h) return h.ip;
  }
  const hit = etcHosts(s.world).find(([, n]) => n === name);
  return hit ? hit[0] : null;
}
function svcState(h) {
  if (!h.svcs) {
    h.svcs = {};
    if (h.kind === 'server') {
      if (h.listen.includes(443)) h.svcs.nginx = 'active';
      if (h.listen.includes(3306)) h.svcs.mysql = 'active';
    }
    if (h.kind === 'svc') h.svcs[{ dns: 'named', ntp: 'chronyd', syslog: 'rsyslog', nms: 'snmpd', dhcp: 'isc-dhcp-server', radius: 'freeradius' }[h.role] || 'sshd'] = 'active';
    h.svcs.sshd = 'active';
  }
  return h.svcs;
}
export function syncListen(h) {
  const sv = svcState(h);
  const ports = new Set();
  for (const [name, st] of Object.entries(sv)) if (st === 'active') (SVC_PORTS[name] || []).forEach((p) => ports.add(p));
  h.listen = [...ports].sort((a, b) => a - b);
}


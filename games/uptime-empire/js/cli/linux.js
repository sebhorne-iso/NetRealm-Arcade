// ping / traceroute / nc / tcpdump
function linuxPing(s, args) {
  let count = null;
  let size = 56;
  let df = false;
  let target = null;
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === '-c') count = Number(args[++i]);
    else if (a === '-s') size = Number(args[++i]);
    else if (a === '-M') df = args[++i] === 'do';
    else if (a === '-W' || a === '-i' || a === '-I' || a === '-t') i++;
    else if (!a.startsWith('-')) target = a;
  }
  if (!target) return 'ping: usage error: Destination address required';
  const ip = resolve(s, target);
  if (!ip) return `ping: ${target}: Name or service not known`;
  const h = s.host;
  const onLink = inNet(ip, `${h.ip}/${h.len || 24}`);
  if (!onLink && !h.gw) return 'ping: connect: Network is unreachable';
  if (h.nic?.up === false) return 'ping: connect: Network is unreachable';
  const n = count || 1e9;
  let sent = 0;
  let recv = 0;
  const rtts = [];
  const header = `PING ${target} (${ip}) ${size}(${size + 28}) bytes of data.\n`;
  let first = true;
  let errs = 0;
  const summary = () => {
    const loss = sent ? Math.round(((sent - recv) / sent) * 100) : 0;
    const lines = [`\n--- ${target} ping statistics ---`, `${sent} packets transmitted, ${recv} received, ${errs ? `+${errs} errors, ` : ''}${loss}% packet loss, time ${Math.max(0, sent - 1) * 1001}ms`];
    if (recv) {
      const mn = Math.min(...rtts);
      const mx = Math.max(...rtts);
      const avg = rtts.reduce((a, b) => a + b, 0) / rtts.length;
      lines.push(`rtt min/avg/max/mdev = ${ip3(mn)}/${ip3(avg)}/${ip3(mx)}/${ip3((mx - mn) / 3)} ms`);
    }
    return lines.join('\n') + '\n';
  };
  return genStream(
    () => {
      if (first) {
        first = false;
        return { d: 50, t: header };
      }
      if (sent >= n) return null;
      sent++;
      const p = ping(s, ip, { count: 1, size: size + 28, df });
      if (p.recv) {
        recv++;
        const t = p.res[0].rtt * 0.31 + (hashStr(`${sent}`) % 100) / 1000;
        rtts.push(t);
        const ttl = p.r.toDevice ? ({ cisco: 255, nxos: 255, asa: 255, iosxr: 255, fortios: 255 }[s.world.devices[p.r.at]?.os] || 64) : 64 - Math.max(0, p.r.hops.length - 1);
        return { d: sent === 1 ? 20 : 1000, t: `${p.r.toDevice ? '' : ''}64 bytes from ${ip}: icmp_seq=${sent} ttl=${ttl} time=${ip3(t)} ms\n`, last: sent >= n ? summary() : null };
      }
      if (/no ARP|no route to host|unreachable/.test(p.r.reason) && onLink) {
        errs++;
        return { d: 1000, t: sent % 3 === 0 ? `From ${h.ip} icmp_seq=${sent - 2} Destination Host Unreachable\nFrom ${h.ip} icmp_seq=${sent - 1} Destination Host Unreachable\nFrom ${h.ip} icmp_seq=${sent} Destination Host Unreachable\n` : '' };
      }
      if (p.r.reason?.startsWith('fragmentation needed') && df) return { d: 1000, t: `From ${p.r.hops[p.r.hops.length - 1]?.ip || h.gw} icmp_seq=${sent} Frag needed and DF set (mtu = 1400)\n` };
      return { d: 1000, t: '' };
    },
    () => `^C${summary()}`,
  );
}
// finite pings end with the summary
function wrapFinite(st) {
  const inner = st;
  let pendingSummary = null;
  let done = false;
  return {
    stream: true,
    next() {
      if (done) return null;
      if (pendingSummary) {
        const t = pendingSummary;
        pendingSummary = null;
        done = true;
        return { d: 0, t };
      }
      const c = inner.next();
      if (!c) {
        done = true;
        return null;
      }
      if (c.last) pendingSummary = c.last;
      return c;
    },
    interrupt: () => {
      done = true;
      return inner.interrupt();
    },
  };
}

function linuxTrace(s, args) {
  const target = args.find((a) => !a.startsWith('-'));
  if (!target) return 'Usage: traceroute [ -46dFITnreAUDV ] [ -f first_ttl ] host [ packetlen ]';
  const ip = resolve(s, target);
  if (!ip) return `${target}: Name or service not known\nCannot handle "host" cmdline arg \`${target}' on position 1 (argc 1)`;
  if (!inNet(ip, `${s.host.ip}/${s.host.len || 24}`) && !s.host.gw) return 'connect: Network is unreachable';
  const { hops } = trace(s, ip);
  const chunks = [{ d: 30, t: `traceroute to ${target} (${ip}), 30 hops max, 60 byte packets\n` }];
  let n = 0;
  for (const hp of hops) {
    n++;
    if (hp.ok) {
      const base = 0.3 + n * 0.6;
      chunks.push({ d: 350, t: ` ${String(n).padStart(2)}  ${hp.name && !/^\d/.test(hp.name) ? hp.name : hp.ip} (${hp.ip})  ${ip3(base)} ms  ${ip3(base * 1.07)} ms  ${ip3(base * 0.96)} ms\n` });
    } else {
      for (let k = n; k <= Math.min(30, n + 4); k++) chunks.push({ d: 900, t: ` ${String(k).padStart(2)}  * * *\n` });
      break;
    }
  }
  return stream(chunks);
}

function nc(s, args) {
  const rest = args.filter((a) => !a.startsWith('-'));
  const [target, port] = rest;
  if (!target || !port) return 'usage: nc [-46CDdFhklNnrStUuvZz] [-I length] [-i interval] [-M ttl] destination [port]';
  const ip = resolve(s, target);
  if (!ip) return `nc: getaddrinfo for host "${target}" port ${port}: Name or service not known`;
  const r = two(s.world, { host: s.host.id }, ip, { proto: 'tcp', dport: Number(port) });
  const name = { 22: 'ssh', 23: 'telnet', 80: 'http', 443: 'https', 3306: 'mysql', 161: 'snmp', 53: 'domain' }[port] || '*';
  if (r.ok) {
    const own = ownerOf(s.world, ip);
    if (own?.dev) {
      const d = own.dev;
      const open = (Number(port) === 22 && d.cfg.svc.ssh) || (Number(port) === 23 && d.cfg.svc.telnet) || (Number(port) === 443 && ['fortios', 'aoscx', 'arubaos'].includes(d.os));
      if (!open || d.state !== 'up') return stream([{ d: 300, t: `nc: connect to ${target} port ${port} (tcp) failed: Connection refused\n` }]);
    }
    return stream([{ d: 200, t: `Connection to ${target} ${port} port [tcp/${name}] succeeded!\n` }]);
  }
  if (/port .* closed/.test(r.reason)) return stream([{ d: 200, t: `nc: connect to ${target} port ${port} (tcp) failed: Connection refused\n` }]);
  return stream([{ d: 3000, t: `nc: connect to ${target} port ${port} (tcp) failed: ${/no route|unreachable/.test(r.reason) ? 'No route to host' : 'Connection timed out'}\n` }]);
}

function curl(s, args) {
  const url = args.find((a) => /^https?:\/\//.test(a) || /^\w/.test(a) && !a.startsWith('-'));
  if (!url) return "curl: try 'curl --help' or 'curl --manual' for more information";
  const m = url.match(/^(https?):\/\/([^/:]+)(?::(\d+))?/) || [null, 'http', url, null];
  const port = Number(m[3] || (m[1] === 'https' ? 443 : 80));
  const host = m[2];
  const ip = host === 'localhost' ? s.host.ip : resolve(s, host) || (/^[\w.-]+\.\w+$/.test(host) ? '93.184.216.34' : null);
  if (!ip) return `curl: (6) Could not resolve host: ${host}`;
  const head = args.includes('-I') || args.includes('--head');
  let ok;
  let reason;
  if (ip === s.host.ip) {
    syncListen(s.host);
    ok = s.host.listen.includes(port);
    reason = ok ? '' : 'refused';
  } else {
    const r = two(s.world, { host: s.host.id }, ip, { proto: 'tcp', dport: port });
    ok = r.ok;
    reason = r.ok ? '' : /closed/.test(r.reason) ? 'refused' : 'timeout';
  }
  if (!ok) return stream([{ d: reason === 'refused' ? 100 : 4000, t: reason === 'refused' ? `curl: (7) Failed to connect to ${host} port ${port} after 2 ms: Connection refused\n` : `curl: (28) Failed to connect to ${host} port ${port} after 130001 ms: Connection timed out\n` }]);
  const body = head ? `HTTP/1.1 200 OK\nServer: nginx/1.18.0 (Ubuntu)\nDate: ${new Date(Date.UTC(1995, 0, 1) + s.world.time.t * 60000).toUTCString()}\nContent-Type: text/html\nConnection: keep-alive\n` : '<!doctype html><html><head><title>It works</title></head><body>OK</body></html>\n';
  return stream([{ d: 150, t: body }]);
}

function tcpdump(s, args) {
  const h = s.host;
  const filter = args.filter((a, i) => !a.startsWith('-') && !['-i', '-c', '-s', '-w'].includes(args[i - 1])).join(' ');
  const cIdx = args.indexOf('-c');
  const limit = cIdx >= 0 ? Number(args[cIdx + 1]) : Infinity;
  const nIdx = args.indexOf('-i');
  const iface = nIdx >= 0 ? args[nIdx + 1] : 'eth0';
  if (iface !== 'eth0' && iface !== 'any' && iface !== 'lo') return `tcpdump: ${iface}: No such device exists\n(SIOCGIFHWADDR: No such device)`;
  const W = s.world;
  const R = rng(`tcpdump:${W.time.t}:${h.id}`);
  const pkts = [];
  // What arrives at this host? Web traffic from the internet probe, monitoring from the NMS, plus ARP
  const nms = Object.values(W.hosts).find((x) => x.role === 'nms');
  S_(W);
  const ts = () => {
    const d = new Date(Date.UTC(1995, 0, 1) + W.time.t * 60000 + pkts.length * 137);
    return `${String(d.getUTCHours()).padStart(2, '0')}:${String(d.getUTCMinutes()).padStart(2, '0')}:${String(d.getUTCSeconds()).padStart(2, '0')}.${String(R.int(0, 999999)).padStart(6, '0')}`;
  };
  const gw = h.gw;
  const gwOk = gw && (W.sim.bySeg.get(W.sim.eps.find((e) => e.host === h.id)?.seg) || []).some((e) => e.ip === gw);
  const push = (t, txt) => pkts.push({ t, txt });
  for (let k = 0; k < 6; k++) {
    if (gw && !gwOk) push('arp', `ARP, Request who-has ${gw} tell ${h.ip}, length 28`);
    const cust = W.design.customers.find((c) => c.servers[0] === h.id && c.web);
    if (cust) {
      const isp = Object.values(W.hosts).find((x) => x.kind === 'isp');
      const f = isp ? walk(W, { host: isp.id }, cust.vip, { proto: 'tcp', dport: 443 }) : null;
      if (f?.ok && f.at === h.id) {
        const src = `198.51.100.${77 + (k % 3)}`;
        const sport = 40000 + R.int(0, 20000);
        push('tcp', `IP ${src}.${sport} > ${h.ip}.443: Flags [S], seq ${R.int(1e8, 4e9)}, win 64240, options [mss 1460,sackOK,TS val ${R.int(1e6, 9e6)} ecr 0,nop,wscale 7], length 0`);
        syncListen(h);
        if (!h.listen.includes(443)) push('tcp', `IP ${h.ip}.443 > ${src}.${sport}: Flags [R.], seq 0, ack 1, win 0, length 0`);
        else {
          push('tcp', `IP ${h.ip}.443 > ${src}.${sport}: Flags [S.], seq ${R.int(1e8, 4e9)}, ack 1, win 65160, options [mss 1460,sackOK,TS val ${R.int(1e6, 9e6)} ecr 1,nop,wscale 7], length 0`);
          const back = walk(W, { host: h.id }, src, { proto: 'tcp', ret: true });
          if (back.ok) push('tcp', `IP ${src}.${sport} > ${h.ip}.443: Flags [.], ack 1, win 502, length 0`);
          else push('tcp', `IP ${src}.${sport} > ${h.ip}.443: Flags [S], seq ${R.int(1e8, 4e9)}, win 64240, options [mss 1460,sackOK,TS val ${R.int(1e6, 9e6)} ecr 0,nop,wscale 7], length 0`);
        }
      }
    }
    if (nms && nms.id !== h.id) {
      const f = walk(W, { host: nms.id }, h.ip, {});
      if (f.ok) {
        push('icmp', `IP ${nms.ip} > ${h.ip}: ICMP echo request, id ${4100 + k}, seq ${k + 1}, length 64`);
        const back = walk(W, { host: h.id }, nms.ip, { ret: true });
        if (back.ok) push('icmp', `IP ${h.ip} > ${nms.ip}: ICMP echo reply, id ${4100 + k}, seq ${k + 1}, length 64`);
      }
    }
  }
  const match = (p) => {
    if (!filter) return true;
    if (/icmp/.test(filter)) return p.t === 'icmp';
    if (/arp/.test(filter)) return p.t === 'arp';
    const port = filter.match(/port (\d+)/);
    if (port) return p.txt.includes(`.${port[1]} `) || p.txt.includes(`.${port[1]}:`);
    const host = filter.match(/host ([\d.]+)/);
    if (host) return p.txt.includes(host[1]);
    return true;
  };
  const list = pkts.filter(match);
  let i = 0;
  let shown = 0;
  const head = `tcpdump: verbose output suppressed, use -v[v]... for full protocol decode\nlistening on ${iface}, link-type EN10MB (Ethernet), snapshot length 262144 bytes\n`;
  let started = false;
  const tail = () => `\n${shown} packets captured\n${shown} packets received by filter\n0 packets dropped by kernel\n`;
  return genStream(
    () => {
      if (!started) {
        started = true;
        return { d: 100, t: head };
      }
      if (shown >= limit) return null;
      if (!list.length) return { d: 1000, t: '' };
      const p = list[i++ % list.length];
      shown++;
      return { d: 400 + R.int(0, 700), t: `${ts()} ${p.txt}\n` };
    },
    () => `^C${tail()}`,
  );
}


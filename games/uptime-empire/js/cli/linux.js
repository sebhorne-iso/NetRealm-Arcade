function ipAddr(s) {
  const h = s.host;
  const mac = macColon(macOfHost(h));
  const up = h.nic?.up !== false;
  return [
    '1: lo: <LOOPBACK,UP,LOWER_UP> mtu 65536 qdisc noqueue state UNKNOWN group default qlen 1000',
    '    link/loopback 00:00:00:00:00:00 brd 00:00:00:00:00:00',
    '    inet 127.0.0.1/8 scope host lo',
    '       valid_lft forever preferred_lft forever',
    `2: eth0: <BROADCAST,MULTICAST${up ? ',UP,LOWER_UP' : ''}> mtu ${h.mtu || 1500} qdisc mq state ${up ? 'UP' : 'DOWN'} group default qlen 1000`,
    `    link/ether ${mac} brd ff:ff:ff:ff:ff:ff`,
    `    inet ${h.ip}/${h.len || 24} brd ${h.ip.split('.').slice(0, 3).join('.')}.255 scope global eth0`,
    '       valid_lft forever preferred_lft forever',
  ].join('\n');
}
function ipRoute(s) {
  const h = s.host;
  const net = `${h.ip.split('.').slice(0, 3).join('.')}.0/${h.len || 24}`;
  const out = [];
  if (h.gw) out.push(`default via ${h.gw} dev eth0 proto static`);
  out.push(`${net} dev eth0 proto kernel scope link src ${h.ip}`);
  return out.join('\n');
}
function ipCmd(s, args) {
  const h = s.host;
  const [obj = '', verb = 'show', ...rest] = args;
  const o = obj.replace(/^-\w+$/, '');
  if (/^a(d(d(r(e(ss?)?)?)?)?)?$/.test(o)) return ipAddr(s);
  if (/^r(o(u(te?)?)?)?$/.test(o)) {
    if (['show', 'list', 'ls'].includes(verb) || !verb) return ipRoute(s);
    if (s.host.kind === 'jump') return 'RTNETLINK answers: Operation not permitted';
    if (['replace', 'add', 'change'].includes(verb)) {
      const vi = rest.indexOf('via');
      if (rest[0] !== 'default' && rest[0] !== '0.0.0.0/0') return 'Error: only the default route can be changed on this server.';
      if (vi < 0) return 'Error: either "to" is duplicate, or "via" is a garbage.';
      if (verb === 'add' && h.gw) return 'RTNETLINK answers: File exists';
      const gw = rest[vi + 1];
      if (!inNet(gw, `${h.ip}/${h.len || 24}`)) return 'Error: Nexthop has invalid gateway.';
      h.gw = gw;
      h.changed = s.world.time.t;
      s.world.dirty = true;
      recompute(s.world);
      return '';
    }
    if (verb === 'del' || verb === 'delete') {
      if (!h.gw) return 'RTNETLINK answers: No such process';
      h.gw = null;
      s.world.dirty = true;
      recompute(s.world);
      return '';
    }
    return `Command "${verb}" is unknown, try "ip route help".`;
  }
  if (/^l(i(nk?)?)?$/.test(o)) {
    if (verb === 'set') {
      const [, dev, state] = [null, ...rest];
      if (dev !== 'eth0') return `Cannot find device "${dev}"`;
      h.nic.up = state !== 'down';
      s.world.dirty = true;
      recompute(s.world);
      return '';
    }
    const up = h.nic?.up !== false;
    return `1: lo: <LOOPBACK,UP,LOWER_UP> mtu 65536 qdisc noqueue state UNKNOWN mode DEFAULT group default qlen 1000\n    link/loopback 00:00:00:00:00:00 brd 00:00:00:00:00:00\n2: eth0: <BROADCAST,MULTICAST${up ? ',UP,LOWER_UP' : ''}> mtu 1500 qdisc mq state ${up ? 'UP' : 'DOWN'} mode DEFAULT group default qlen 1000\n    link/ether ${macColon(macOfHost(h))} brd ff:ff:ff:ff:ff:ff`;
  }
  if (/^n(e(i(gh?)?)?)?$/.test(o)) {
    S_(s.world);
    const ep = s.world.sim.eps.find((e) => e.host === h.id);
    const seg = s.world.sim.bySeg.get(ep?.seg) || [];
    const gw = seg.find((e) => e.ip === h.gw);
    return h.gw ? (gw ? `${h.gw} dev eth0 lladdr 00:00:0c:07:ac:01 REACHABLE` : `${h.gw} dev eth0 FAILED`) : '';
  }
  return `Object "${obj}" is unknown, try "ip help".`;
}
function ethtool(s, args) {
  const h = s.host;
  const W = s.world;
  if (args[0] === '-s') {
    const i = (k) => args[args.indexOf(k) + 1];
    if (args.includes('autoneg') && i('autoneg') === 'on') {
      h.nic.speed = 'auto';
      h.nic.duplex = 'auto';
    } else {
      if (args.includes('speed')) h.nic.speed = Number(i('speed'));
      if (args.includes('duplex')) h.nic.duplex = i('duplex');
    }
    W.dirty = true;
    recompute(W);
    return '';
  }
  const S = S_(W);
  const p = S.peerOf.get(`h:${h.id}`);
  const L = p ? S.links[p.link.id] : null;
  if (args[0] === '-S') {
    const crc = L?.errors ? Math.floor((W.time.t % 10000) * 3.7) : 0;
    return `NIC statistics:\n     rx_packets: ${Math.floor(W.time.t * 913)}\n     tx_packets: ${Math.floor(W.time.t * 611)}\n     rx_crc_errors: ${crc}\n     rx_missed_errors: 0\n     tx_late_coll: ${L?.duplex === 'mismatch' ? Math.floor(crc / 3) : 0}\n     tx_deferred_ok: ${L?.duplex === 'mismatch' ? crc * 2 : 0}`;
  }
  const up = L?.up;
  const dup = L?.duplex === 'mismatch' ? (h.nic.duplex === 'auto' ? 'Half' : h.nic.duplex === 'half' ? 'Half' : 'Full') : 'Full';
  return [
    'Settings for eth0:',
    '\tSupported ports: [ TP ]',
    '\tSupported link modes:   10baseT/Half 10baseT/Full',
    '\t                        100baseT/Half 100baseT/Full',
    '\t                        1000baseT/Full',
    `\tSpeed: ${up ? `${L.speed}Mb/s` : 'Unknown!'}`,
    `\tDuplex: ${up ? dup : 'Unknown! (255)'}`,
    '\tPort: Twisted Pair',
    `\tAuto-negotiation: ${h.nic.speed === 'auto' && h.nic.duplex === 'auto' ? 'on' : 'off'}`,
    `\tLink detected: ${up ? 'yes' : 'no'}`,
  ].join('\n');
}
function systemctl(s, args) {
  const h = s.host;
  const sv = svcState(h);
  const verb = args.find((a) => !a.startsWith('-')) || 'status';
  const name = (args.filter((a) => !a.startsWith('-'))[1] || '').replace(/\.service$/, '');
  if (!name) {
    if (verb === 'status' || verb === 'list-units') return Object.entries(sv).map(([n, st]) => `  ${(n + '.service').padEnd(28)} loaded ${st === 'active' ? 'active   running' : 'failed   failed '} ${n}`).join('\n');
    return 'Too few arguments.';
  }
  if (!(name in sv)) return `Unit ${name}.service could not be found.`;
  if (verb === 'status') {
    const st = sv[name];
    const since = fmtDate(h.svcSince?.[name] ?? 0, 'datetime');
    return [
      `${st === 'active' ? '●' : '×'} ${name}.service - ${name === 'nginx' ? 'A high performance web server and a reverse proxy server' : name}`,
      `     Loaded: loaded (/lib/systemd/system/${name}.service; enabled; vendor preset: enabled)`,
      `     Active: ${st === 'active' ? `active (running) since ${since} UTC` : `failed (Result: ${h.svcWhy?.[name] || 'signal'}) since ${since} UTC`}`,
      ...(st === 'active' ? [`   Main PID: ${1000 + (hashStr(name) % 8000)} (${name})`] : ['    Process: 1187 ExecStart=/usr/sbin/nginx (code=killed, signal=KILL)']),
      '',
      ...journal(h, name).slice(-3),
    ].join('\n');
  }
  if (['start', 'restart', 'reload'].includes(verb)) {
    sv[name] = 'active';
    (h.svcSince = h.svcSince || {})[name] = s.world.time.t;
    syncListen(h);
    s.world.dirty = true;
    logEvent(s.world, null, { type: 'svc', host: h.id, svc: name, up: true });
    return '';
  }
  if (verb === 'stop') {
    sv[name] = 'inactive';
    syncListen(h);
    s.world.dirty = true;
    return '';
  }
  if (verb === 'enable' || verb === 'disable') return `${verb === 'enable' ? 'Created' : 'Removed'} symlink /etc/systemd/system/multi-user.target.wants/${name}.service.`;
  return `Unknown command verb ${verb}.`;
}
function journal(h, name) {
  const out = [];
  const t = h.svcSince?.[name] ?? 0;
  const st = h.svcs?.[name];
  const stamp = fmtDate(t, 'syslog');
  out.push(`${stamp} ${h.name} systemd[1]: Started ${name}.service.`);
  if (st !== 'active' && h.svcWhy?.[name] === 'oom-kill') {
    out.push(`${stamp} ${h.name} kernel: Out of memory: Killed process 1187 (${name}) total-vm:2101432kB, anon-rss:1884320kB`);
    out.push(`${stamp} ${h.name} systemd[1]: ${name}.service: Main process exited, code=killed, status=9/KILL`);
    out.push(`${stamp} ${h.name} systemd[1]: ${name}.service: Failed with result 'oom-kill'.`);
  } else if (st !== 'active') out.push(`${stamp} ${h.name} systemd[1]: ${name}.service: Failed with result 'signal'.`);
  return out;
}
function ss(s) {
  syncListen(s.host);
  const rows = ['State   Recv-Q  Send-Q   Local Address:Port    Peer Address:Port  Process'];
  for (const p of s.host.listen) {
    const name = Object.entries(SVC_PORTS).find(([n, ps]) => ps.includes(p) && s.host.svcs?.[n] === 'active')?.[0] || 'sshd';
    rows.push(`LISTEN  0       511            0.0.0.0:${String(p).padEnd(10)}       0.0.0.0:*      users:(("${name}",pid=${1000 + (hashStr(name) % 8000)},fd=6))`);
  }
  return rows.join('\n');
}


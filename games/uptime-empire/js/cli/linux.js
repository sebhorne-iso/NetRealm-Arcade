// ssh / telnet / console
function connectDevice(s, target, { proto, user, via = 'vty' }) {
  const W = s.world;
  const ip = resolve(s, target);
  if (!ip) return proto === 'ssh' ? `ssh: Could not resolve hostname ${target}: Name or service not known` : `telnet: could not resolve ${target}/telnet: Name or service not known`;
  const port = proto === 'ssh' ? 22 : 23;
  const r = two(W, { host: s.host.id }, ip, { proto: 'tcp' });
  const own = ownerOf(W, ip);
  const pre = proto === 'telnet' ? `Trying ${ip}...\n` : '';
  if (!r.ok || !own || (own.dev && own.dev.state !== 'up')) {
    const msg = /no route|no gateway|unreachable \(no ARP/.test(r.reason || '') && inNet(ip, `${s.host.ip}/24`) ? 'No route to host' : 'Connection timed out';
    return stream([{ d: 10, t: pre }, { d: msg === 'No route to host' ? 3000 : 6000, t: proto === 'ssh' ? `ssh: connect to host ${ip} port ${port}: ${msg}\n` : `telnet: Unable to connect to remote host: ${msg}\n` }]);
  }
  if (own.host) {
    if (proto === 'telnet') return stream([{ d: 10, t: pre }, { d: 200, t: 'telnet: Unable to connect to remote host: Connection refused\n' }]);
    return openServer(s, own.host, 'ssh');
  }
  const dev = own.dev;
  const allowed = proto === 'ssh' ? dev.cfg.svc.ssh : dev.cfg.svc.telnet;
  if (!allowed) return stream([{ d: 10, t: pre }, { d: 250, t: proto === 'ssh' ? `ssh: connect to host ${ip} port 22: Connection refused\n` : 'telnet: Unable to connect to remote host: Connection refused\n' }]);
  const D = getDialect(dev.os);
  const login = (u) => {
    let tries = 0;
    const pwPrompt = proto === 'ssh' ? `${u}@${ip}'s password: ` : 'Password: ';
    const check = (pw) => {
      const acct = dev.cfg.svc.users.find((x) => x.name === u);
      if (acct && acct.pw === pw) {
        logEvent(W, dev.id, { type: 'login', user: u, from: s.host.ip, proto });
        const sess = new Session(null, { world: W, dialect: D, dev, via, user: u, from: s, priv: acct.priv ?? 15 });
        return { push: sess, text: proto === 'telnet' ? '' : '' };
      }
      tries++;
      logEvent(W, dev.id, { type: 'authfail', user: u, from: s.host.ip, proto });
      if (tries >= 3) return proto === 'ssh' ? `${u}@${ip}: Permission denied (publickey,keyboard-interactive,password).` : '% Authentication failed\nConnection closed by foreign host.';
      return { ...ask(pwPrompt, check, { hidden: true }), pre: proto === 'ssh' ? 'Permission denied, please try again.\n' : '% Login invalid\n\n' };
    };
    return ask(pwPrompt, check, { hidden: true });
  };
  if (proto === 'telnet') {
    const banner = D.telnetBanner ? D.telnetBanner(dev) : '';
    const first = ask(D.loginPrompt ? D.loginPrompt(dev) : 'Username: ', (u) => login(u.trim() || 'admin'));
    return { ...first, pre: `${pre}Connected to ${ip}.\nEscape character is '^]'.\n${banner}` };
  }
  // SSH host key check
  const js = jumpState(W);
  const known = js.known[ip];
  if (known && known !== dev.key) {
    return [
      '@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@',
      '@    WARNING: REMOTE HOST IDENTIFICATION HAS CHANGED!     @',
      '@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@',
      'IT IS POSSIBLE THAT SOMEONE IS DOING SOMETHING NASTY!',
      'Someone could be eavesdropping on you right now (man-in-the-middle attack)!',
      'It is also possible that a host key has just been changed.',
      'The fingerprint for the RSA key sent by the remote host is',
      `${dev.key}.`,
      'Please contact your system administrator.',
      'Add correct host key in /home/netops/.ssh/known_hosts to get rid of this message.',
      `Offending RSA key in /home/netops/.ssh/known_hosts:${Object.keys(js.known).indexOf(ip) + 1}`,
      '  remove with:',
      `  ssh-keygen -f "/home/netops/.ssh/known_hosts" -R "${ip}"`,
      `Host key for ${ip} has changed and you have requested strict checking.`,
      'Host key verification failed.',
    ];
  }
  if (!known) {
    const q = (ans) => {
      const a = ans.trim().toLowerCase();
      if (a === 'yes' || a === dev.key.toLowerCase()) {
        js.known[ip] = dev.key;
        return { ...login(user), pre: `Warning: Permanently added '${ip}' (RSA) to the list of known hosts.\n` };
      }
      if (a === 'no') return 'Host key verification failed.';
      return ask("Please type 'yes', 'no' or the fingerprint: ", q);
    };
    return { ...ask('Are you sure you want to continue connecting (yes/no/[fingerprint])? ', q), pre: `The authenticity of host '${ip} (${ip})' can't be established.\nRSA key fingerprint is ${dev.key}.\nThis key is not known by any other names\n` };
  }
  return login(user);
}

function openServer(s, h, via) {
  const sess = new Session(null, { world: s.world, dialect: LINUX, host: h, via, user: 'root', from: s });
  return { push: sess };
}

export function openConsole(world, term, name, from = null) {
  const dev = Object.values(world.devices).find((d) => d.hostname === name || d.id === name);
  const host = !dev && Object.values(world.hosts).find((h) => h.name === name && (h.kind === 'server' || h.kind === 'svc'));
  if (!dev && !host) return null;
  if (host) return new Session(term, { world, dialect: LINUX, host, via: 'console', user: 'root', from });
  const D = getDialect(dev.os);
  return new Session(term, { world, dialect: D, dev, via: 'console', user: 'console', from, priv: 15 });
}

function consoleCmd(s, args) {
  const name = args[0];
  if (!name) return 'usage: console <device|server>   (console server / IPMI serial-over-LAN)';
  const sess = openConsole(s.world, s.term, name, s);
  if (!sess) return `console: ${name}: no such port on console server cs01`;
  const port = 1 + (hashStr(name) % 47);
  if (sess.dev && sess.dev.state === 'off') return { push: sess, text: `Connecting to ${name} via cs01 port ${port} (9600 8N1) - escape sequence is ~.\n\n` };
  if (sess.dev?.dialect?.consoleLogin || sess.dialect.consoleLogin) {
    const D = sess.dialect;
    const login = () => {
      const dev = sess.dev;
      const userQ = (u) =>
        ask('Password:', (pw) => {
          const acct = dev.cfg.svc.users.find((x) => x.name === u.trim());
          if (acct && acct.pw === pw) {
            sess.user = acct.name;
            logEvent(s.world, dev.id, { type: 'login', user: acct.name, from: 'console', proto: 'console' });
            return { push: sess };
          }
          logEvent(s.world, dev.id, { type: 'authfail', user: u.trim(), from: 'console', proto: 'console' });
          return { ...ask(D.loginPrompt(dev), userQ), pre: 'Login incorrect\n' };
        }, { hidden: true });
      return { ...ask(D.loginPrompt(dev), userQ), pre: `Connecting to ${name} via cs01 port ${port} (9600 8N1) - escape sequence is ~.\n\n${D.consoleBanner ? D.consoleBanner(dev) : ''}` };
    };
    return login();
  }
  return { push: sess, text: `Connecting to ${name} via cs01 port ${port} (9600 8N1) - escape sequence is ~.\n` };
}

